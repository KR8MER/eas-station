def test_page_uses_only_defined_css_variables():
    """The old page painted with --gradient-start/--gradient-end, which never existed."""
    styles = (REPO_ROOT / 'static' / 'css' / 'styles.css').read_text(encoding='utf-8')
    sources = [
        (REPO_ROOT / 'templates' / 'repo_stats.html').read_text(encoding='utf-8'),
        (REPO_ROOT / 'templates' / 'repo_stats' / '_content.html').read_text(encoding='utf-8'),
        (REPO_ROOT / 'templates' / 'repo_stats' / '_scripts.html').read_text(encoding='utf-8'),
    ]

    import re
    used = set()
    for source in sources:
        used.update(re.findall(r'var\(\s*(--[a-z0-9-]+)', source))
        used.update(re.findall(r"cssVar\(\s*'(--[a-z0-9-]+)'", source))

    assert used, 'expected the page to use theme variables'
    undefined = sorted(name for name in used if f'{name}:' not in styles)
    assert not undefined, f'page references undefined CSS variables: {undefined}'


