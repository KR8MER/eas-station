"""Tests for the live repository statistics page.

The statistics used to be a committed ``static/repo_stats.html`` blob
regenerated by a script, so the tests could only assert on stale strings. The
page is now computed on demand from the working tree, so these tests exercise
the analyser itself: bucket classification, line counting, caching, and that
the page and its JSON sibling render.
"""

from pathlib import Path

import pytest

from app_utils import repo_stats


REPO_ROOT = Path(__file__).resolve().parent.parent


@pytest.fixture(autouse=True)
def _clear_cache():
    """Each test starts from a cold cache."""
    repo_stats.invalidate_cache()
    yield
    repo_stats.invalidate_cache()


@pytest.fixture(scope='module')
def sample_tree(tmp_path_factory):
    """A tiny repository-shaped tree with one file per bucket."""
    root = tmp_path_factory.mktemp('sample_repo')

    (root / 'webapp').mkdir()
    (root / 'webapp' / 'views.py').write_text(
        '"""Module docstring."""\n'
        '\n'
        '# a comment\n'
        'import os\n'
        '\n'
        'def handler():\n'
        '    return os.getcwd()\n',
        encoding='utf-8',
    )

    (root / 'docs').mkdir()
    (root / 'docs' / 'GUIDE.md').write_text('# Guide\n\nSome prose.\n', encoding='utf-8')

    vendor = root / 'static' / 'vendor' / 'chartjs'
    vendor.mkdir(parents=True)
    (vendor / 'chart.min.js').write_text('var Chart=function(){};\n', encoding='utf-8')

    return root


