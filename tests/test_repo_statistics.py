def test_python_line_counting(tmp_path):
    source = tmp_path / 'module.py'
    source.write_text(
        '"""One-line docstring."""\n'   # comment (must not open a block)
        '# comment\n'                   # comment
        'x = 1\n'                       # code
        '\n'                            # blank
        '"""\n'                         # comment (opens block)
        'block\n'                       # comment
        '"""\n'                         # comment (closes block)
        'y = 2\n',                      # code
        encoding='utf-8',
    )

    total, code, comments = repo_stats.count_lines(source, '.py')
    assert total == 8
    assert code == 2, 'a one-line docstring must not swallow the rest of the file'
    assert comments == 5
    assert total - code - comments == 1, 'one blank line'


def test_unreadable_file_is_counted_as_zero(tmp_path):
    missing = tmp_path / 'not-there.py'
    assert repo_stats.count_lines(missing, '.py') == (0, 0, 0)


