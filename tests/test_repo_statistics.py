def test_real_repository_snapshot_is_sane():
    stats = repo_stats.compute_stats()

    assert stats['file_source'] in {'git', 'walk'}
    assert stats['total_files'] > 100
    assert stats['directories'] > 10

    project = stats['buckets']['project']
    assert project['files'] > 100
    assert project['code'] > 10000
    assert project['blank'] >= 0
    assert project['languages'], 'expected a language breakdown'
    assert project['languages'][0]['name'] == 'Python'

    components = stats['components']
    assert components['templates'] > 50
    assert components['tests'] > 50
    assert components['migrations'] > 50
    assert components['blueprints'] > 5
    assert components['models'] > 5


def test_route_count_includes_named_blueprints():
    """The old regex only matched @app.route/@bp.route and missed ~half the app."""
    stats = repo_stats.compute_stats()
    assert stats['routes']['total'] > 400, (
        'route count looks like the old @app|@bp-only regex'
    )
    assert stats['routes']['by_module'], 'expected a per-module breakdown'


def test_cache_is_reused_until_invalidated():
    first = repo_stats.get_stats()
    second = repo_stats.get_stats()
    assert first is second, 'a warm cache must not recompute'

    repo_stats.invalidate_cache()
    third = repo_stats.get_stats()
    assert third is not first


def test_generated_stats_are_json_serialisable():
    import json

    stats = repo_stats.compute_stats()
    round_tripped = json.loads(json.dumps(stats))
    assert round_tripped['total_files'] == stats['total_files']


