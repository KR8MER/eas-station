def test_vendored_assets_are_not_counted_as_project_code(sample_tree):
    """The bug the old page shipped: vendor code inflating the headline totals."""
    stats = repo_stats.compute_stats(root=sample_tree)

    project = stats['buckets']['project']
    vendored = stats['buckets']['vendored']

    assert project['files'] == 1, 'only webapp/views.py is first-party here'
    assert vendored['files'] == 1, 'chart.min.js must land in the vendored bucket'
    assert vendored['code'] > 0
    # The vendored line must not appear anywhere in the project totals.
    assert project['code'] < vendored['code'] + project['total']
    assert stats['buckets']['docs']['files'] == 1


def test_buckets_partition_all_files(sample_tree):
    """Every counted file belongs to exactly one bucket."""
    stats = repo_stats.compute_stats(root=sample_tree)
    bucketed = sum(stats['buckets'][name]['files'] for name in repo_stats.BUCKETS)
    assert bucketed == stats['total_files']


