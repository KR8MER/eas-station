def test_old_generated_artifacts_are_gone():
    """The stale generate-and-commit pipeline must stay deleted."""
    assert not (REPO_ROOT / 'static' / 'repo_stats.html').exists()
    assert not (REPO_ROOT / 'scripts' / 'generate_repo_stats.py').exists()
    assert not (REPO_ROOT / '.github' / 'workflows' / 'update-repo-stats.yml').exists()


def test_page_template_extends_base_and_uses_standard_header():
    page = (REPO_ROOT / 'templates' / 'repo_stats.html').read_text(encoding='utf-8')
    content = (REPO_ROOT / 'templates' / 'repo_stats' / '_content.html').read_text(encoding='utf-8')

    assert '{% extends "base.html" %}' in page
    assert "{% include 'components/page_header.html' %}" in content
    assert '{% block scripts %}' in page, 'page JS must use the real block name'
    assert '{% block extra_js %}' not in page

    # Chart.js must come from the vendored copy, never a CDN.
    assert "vendor/chartjs/chart.min.js" in page
    assert 'cdn.jsdelivr.net' not in page and 'cdnjs.cloudflare.com' not in page


def test_page_uses_only_defined_css_variables():
    """The old page painted with --gradient-start/--gradient-end, which never existed."""
    styles = (REPO_ROOT / 'static' / 'css' / 'styles.css').read_text(encoding='utf-8')
    sources = [
        (REPO_ROOT / 'templates' / 'repo_stats.html').read_text(encoding='utf-8'),
        (REPO_ROOT / 'templates' / 'repo_stats' / '_content.html').read_text(encoding='utf-8'),
        (REPO_ROOT / 'templates' / 'repo_stats' / '_scripts.html').read_text(encoding='utf-8'),
    ]

    import re
    used = set()
    for source in sources:
        used.update(re.findall(r'var\(\s*(--[a-z0-9-]+)', source))
        used.update(re.findall(r"cssVar\(\s*'(--[a-z0-9-]+)'", source))

    assert used, 'expected the page to use theme variables'
    undefined = sorted(name for name in used if f'{name}:' not in styles)
    assert not undefined, f'page references undefined CSS variables: {undefined}'


def test_repo_stats_is_registered_in_navigation():
    from webapp.navigation import registry

    hrefs = []
    for section in registry.NAVIGATION:
        for group in section.groups:
            for item in group.items:
                hrefs.append(item.href)

    assert '/repo-stats' in hrefs, 'the page must be reachable from the nav registry'
